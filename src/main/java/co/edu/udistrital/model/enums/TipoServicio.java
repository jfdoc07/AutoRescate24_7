package co.edu.udistrital.model.enums;

/**
 * Representa los diferentes tipos de servicios que pueden ser atendidos
 * por el sistema AutoRescate 24/7.
 *
 * @author Santiago Aroca, Fernando Cárdenas y Daniel Molano.
 */
public enum TipoServicio {

    /**
     * Servicio de cambio de llanta.
     */
    CAMBIO_LLANTA,

    /**
     * Servicio de paso de corriente para vehículos descargados.
     */
    PASO_CORRIENTE,

    /**
     * Servicio de remolque mediante grúa.
     */
    GRUA,

    /**
     * Servicio de apertura de puertas para vehículos bloqueados.
     */
    APERTURA_PUERTAS,

    /**
     * Servicio de suministro de combustible.
     */
    COMBUSTIBLE,

    /**
     * Servicio de revisión mecánica básica.
     */
    REVISION_MECANICA
}
