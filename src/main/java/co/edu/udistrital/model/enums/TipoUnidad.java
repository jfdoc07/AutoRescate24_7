package co.edu.udistrital.model.enums;

/**
 * Representa los tipos de unidades de servicio disponibles
 * en el sistema AutoRescate 24/7.
 *
 * @author Santiago Aroca, Fernando Cárdenas y Daniel Molano.
 */
public enum TipoUnidad {

    /**
     * Unidad especializada en remolque de vehículos.
     */
    GRUA,

    /**
     * Motocicleta utilizada para servicios de rápida respuesta.
     */
    MOTO,

    /**
     * Camioneta equipada para atención de distintos servicios.
     */
    CAMIONETA,

    /**
     * Vehículo liviano destinado a la prestación de servicios operativos.
     */
    VEHICULO_LIVIANO
}
