    /**
     * Este método se encarga de colorear todos los contenidos dentro de los
     * contenedores.
     *
     * @param contenedor el JPanel principal. Toma todos los elementos al
     * interior y los colorea, les da estilos.
     */
    private void pintarFondo(java.awt.Container contenedor) {
        contenedor.setBackground(new Color(26, 26, 46));

        for (java.awt.Component c : contenedor.getComponents()) {
            if (c instanceof javax.swing.JPanel) {
                ((javax.swing.JPanel) c).setOpaque(true);
                ((javax.swing.JPanel) c).setBackground(new Color(26, 26, 46));
                pintarFondo((java.awt.Container) c); // recursivo para paneles anidados
            }
            if (c instanceof javax.swing.JLabel) {
                ((javax.swing.JLabel) c).setForeground(new Color(238, 238, 238));
            }
            if (c instanceof javax.swing.JTextField) {
                javax.swing.JTextField tf = (javax.swing.JTextField) c;
                tf.setBackground(new Color(26, 26, 46));
                tf.setForeground(new Color(238, 238, 238));
                tf.setCaretColor(new Color(238, 238, 238));
                tf.setOpaque(true);
                tf.setBorder(javax.swing.BorderFactory.createCompoundBorder(
                        javax.swing.BorderFactory.createMatteBorder(0, 0, 2, 0, new Color(233, 69, 96)),
                        javax.swing.BorderFactory.createEmptyBorder(4, 6, 4, 6)
                ));
            }
            if (c instanceof javax.swing.JComboBox) {
                ((javax.swing.JComboBox) c).setBackground(new Color(22, 33, 62));
                ((javax.swing.JComboBox) c).setForeground(new Color(238, 238, 238));
            }
            if (c instanceof javax.swing.JButton) {
                estilizarBoton((javax.swing.JButton) c);
            }
        }
    }

    private void estilizarBoton(javax.swing.JButton btn) {
        btn.setBackground(new Color(233, 69, 96));
        btn.setForeground(Color.WHITE);
        btn.setFocusPainted(false);
        btn.setBorderPainted(false);
        btn.setOpaque(true);
    }

